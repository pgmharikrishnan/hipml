#!/usr/bin/env python3
"""Generate crates/hipml-core/src/unicode_tables.rs from llama.cpp's tables.

The pretokenizer's general-category tests must be llama.cpp's, not Rust's
`char::is_alphabetic` approximations: `is_alphabetic` includes the
Other_Alphabetic property (many Mn/Mc marks), and Rust's own Unicode version
drifts from the one the reference binary was built with.

Source: src/unicode-data.cpp at the llama.cpp commit the reference server was
built from (d7725699). Only the four bits the qwen35 splitter reads are kept:
NUMBER (\\p{N}), LETTER (\\p{L}), ACCENT_MARK (\\p{M}) and WHITESPACE (\\s).
Codepoints outside every range are "other" (punctuation/symbol/control/
unassigned); llama.cpp still treats those as one class here.

Usage:
    curl -sO https://raw.githubusercontent.com/ggml-org/llama.cpp/d7725699/src/unicode-data.cpp
    python3 bench/tokenizer/gen_unicode_table.py unicode-data.cpp \
        crates/hipml-core/src/unicode_tables.rs
"""

import re
import sys

NUMBER, LETTER, MARK, WS = 1, 2, 4, 8

src = open(sys.argv[1], encoding="utf-8").read()
out_path = sys.argv[2]

block = re.search(r"unicode_ranges_flags = \{.*?\n\};", src, re.S).group(0)
rows = [(int(a, 16), int(b, 16))
        for a, b in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", block)]
rows = [r for r in rows if r[1] != 0]  # drop the 0x110000 sentinel

ws = re.search(r"unicode_set_whitespace = \{(.*?)\n\};", src, re.S).group(1)
ws_set = {int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]+)", ws)}

spans = []
for i in range(len(rows) - 1):
    start, flags = rows[i]
    end = rows[i + 1][0]
    bits = 0
    if flags & 0x0002:
        bits |= NUMBER
    if flags & 0x0004:
        bits |= LETTER
    if flags & 0x0010:
        bits |= MARK
    # whitespace is a sparse set; split the range where it applies
    cur = start
    cur_bits = bits | (WS if cur in ws_set else 0)
    for cp in range(start + 1, end):
        b = bits | (WS if cp in ws_set else 0)
        if b != cur_bits:
            spans.append((cur, cp, cur_bits))
            cur, cur_bits = cp, b
    spans.append((cur, end, cur_bits))

merged = []
for a, b, v in spans:
    if merged and merged[-1][1] == a and merged[-1][2] == v:
        merged[-1] = (merged[-1][0], b, v)
    else:
        merged.append((a, b, v))
merged = [r for r in merged if r[2] != 0]

entries = [f"(0x{a:X}, 0x{b:X}, {v})," for a, b, v in merged]
lines = ["    " + " ".join(entries[i:i + 10]) for i in range(0, len(entries), 10)]

header = '''//! Unicode category bits, generated from llama.cpp's `unicode-data.cpp`.
//!
//! Do not edit by hand: regenerate with
//! `bench/tokenizer/gen_unicode_table.py unicode-data.cpp \\`
//! `crates/hipml-core/src/unicode_tables.rs`.
//!
//! Only ranges with a bit the qwen35 pretokenizer reads are stored: `NUMBER`
//! (`\\p{N}`), `LETTER` (`\\p{L}`), `MARK` (`\\p{M}`) and `WHITESPACE`
//! (`\\s`). Every codepoint outside a range has none of them, which is the
//! reference's "other" class (punctuation, symbol, control, unassigned).
//!
//! Provenance: llama.cpp d7725699 (the reference server), Unicode tables as
//! generated by its `scripts/gen-unicode-data.py`.

/// `\\p{N}`.
pub const NUMBER: u8 = 1;
/// `\\p{L}`.
pub const LETTER: u8 = 2;
/// `\\p{M}`.
pub const MARK: u8 = 4;
/// `\\s` (Unicode White_Space).
pub const WHITESPACE: u8 = 8;

/// Sorted, non-overlapping `(first, last_exclusive, bits)` ranges.
pub const RANGES: &[(u32, u32, u8)] = &[
'''
with open(out_path, "w", encoding="utf-8") as f:
    f.write(header)
    f.write("\n".join(lines))
    f.write("\n];\n")
    f.write('''
/// The four flags for one codepoint. `0` means "other".
pub fn bits(c: char) -> u8 {
    let cp = c as u32;
    let mut lo = 0usize;
    let mut hi = RANGES.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        let (first, last, v) = RANGES[mid];
        if cp < first {
            hi = mid;
        } else if cp >= last {
            lo = mid + 1;
        } else {
            return v;
        }
    }
    0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn categories_from_the_reference_table() {
        assert_eq!(bits('a'), LETTER);
        assert_eq!(bits('7'), NUMBER);
        assert_eq!(bits(' '), WHITESPACE);
        assert_eq!(bits('\\u{0301}'), MARK); // combining acute
        assert_eq!(bits('\\u{FE0F}'), MARK); // VS16: the case Rust's is_mark missed
        assert_eq!(bits('\\u{2764}'), 0); // heart: symbol, "other"
        assert_eq!(bits('\\u{4E16}'), LETTER); // CJK
        assert_eq!(bits('\\u{0300}'), MARK);
        assert_eq!(bits('\\u{200D}'), 0); // ZWJ: control/format
        assert_eq!(bits('\\u{00A0}'), WHITESPACE); // NBSP
        assert_eq!(bits('\\u{00B2}'), NUMBER); // superscript two is No
        assert_eq!(bits('\\u{2160}'), NUMBER); // Roman numeral one is Nl
    }
}
''')
print(f"{len(merged)} ranges -> {out_path}")
